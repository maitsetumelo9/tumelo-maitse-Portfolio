"use strict";
const assert = require("node:assert/strict");
const { classify, analyze } = require("./analyzer.js");
assert.equal(classify("203.0.113.10").type, "IPv4");
assert.equal(classify("192.168.1.10").risk, "context");
assert.equal(classify("example.com").type, "Domain");
assert.equal(classify("http://example.com/login").risk, "review");
assert.equal(classify("a".repeat(64)).type, "SHA-256");
assert.equal(classify("a".repeat(40)).type, "SHA-1");
assert.equal(classify("a".repeat(32)).type, "MD5");
assert.equal(classify("not a valid indicator").risk, "invalid");
const report = analyze("# sample\n203.0.113.10\nexample.com\n203.0.113.10\n");
assert.equal(report.total, 2, "deduplicates repeated indicators");
assert.equal(report.results[0].line, 2);
assert.equal(report.errors.length, 0);
assert.match(report.disclaimer, /No network requests/);
const invalid = analyze("bad input");
assert.equal(invalid.errors.length, 1);
console.log("IOC analyzer tests passed.");
